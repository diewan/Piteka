//! Piteka HTTP API — first-slice endpoints for action requests and approvals.
//!
//! This crate implements the REST surface described in Master Plan §59 D-07.
//! It exposes stable JSON error shapes, idempotent mutations via `Idempotency-Key`,
//! and an OpenAPI contract checked in CI.
//!
//! # Endpoints
//!
//! | Method | Path | Description |
//! |--------|------|-------------|
//! | `GET`  | `/api/v1/action-requests` | List all action requests |
//! | `GET`  | `/api/v1/action-requests/{id}` | Get a single action request |
//! | `POST` | `/api/v1/action-requests` | Propose a new action request |
//! | `POST` | `/api/v1/action-requests/{id}/approve` | Approve an action request |
//! | `POST` | `/api/v1/action-requests/{id}/reject` | Reject an action request |
//! | `POST` | `/api/v1/action-requests/{id}/revoke` | Revoke an approved request |
//!
//! # Idempotency
//!
//! The `propose`, `approve`, `reject`, and `revoke` endpoints honour the
//! `Idempotency-Key` header. When present, a second call with the same key
//! returns the original result without re-executing the mutation.
//!
//! # OpenAPI
//!
//! The contract lives in `openapi/openapi.yaml` and is checked in CI.
//! The schema is derived from the request/response types in this crate.

